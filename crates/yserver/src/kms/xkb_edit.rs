    /// xkbcommon (like xkbcomp) keeps one modifier per key in its modmap: a
    /// key listed under two `modifier_map`s ends up in the last one only.
    /// The core modmap allows several, so such a map can't go through the
    /// text and must be refused, not silently collapsed.
    #[test]
    fn set_modifier_map_refuses_a_key_in_two_modifiers() {
        let km = golden_keymap("us", None);
        let mut modmap = keymap_modmap(&km);
        modmap[50] |= 0x20; // LFSH: Shift and Mod3
        let collapsed = {
            let mut text = dump(&km);
            text = text.replace(
                "\tmodifier_map Mod3 { <LVL5> };",
                "\tmodifier_map Mod3 { <LVL5>, <LFSH> };",
            );
            keymap_modmap(&compile(&text))[50]
        };
        assert_eq!(
            collapsed.count_ones(),
            1,
            "xkbcommon collapses to one modifier"
        );
        assert_eq!(
            set_modifier_map(&dump(&km), &modmap),
            Err(XkbEditError::MultipleModifiers(50))
        );
    }

    #[test]
    fn set_modifier_map_names_an_unnamed_keycode() {
        let km = golden_keymap("us", None);
        let (named, name) = ensure_keycode_name(&dump(&km), 8).expect("name");
        let spec = spec_of(&km, 133); // LWIN
        let with_key = set_key(&named, &name, &spec).expect("set");
        let mut modmap = keymap_modmap(&km);
        modmap[8] = 0x20; // Mod3
        let text = set_modifier_map(&with_key, &modmap).expect("modmap");
        assert_eq!(keymap_modmap(&compile(&text)), modmap);

        // Without a prior name, set_modifier_map names the keycode itself.
        let mut modmap2 = keymap_modmap(&km);
        modmap2[8] = 0x20;
        let out2 = set_modifier_map(&dump(&km), &modmap2).expect("modmap");
        let after2 = compile(&out2);
        assert!(after2.key_get_name(Keycode::new(8)).is_some());
        assert_eq!(keymap_modmap(&after2), modmap2);
    }
