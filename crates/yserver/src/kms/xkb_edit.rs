    #[test]
    fn set_key_keeps_explicit_repeat_vmods_and_actions() {
        // Give <CAPS> explicit properties the fixtures don't carry, and take
        // xkbcommon's own dump of that as the input, so the input is in the
        // serializer's format.
        let km = golden_keymap("us", None);
        let text = dump(&km);
        let caps = "\tkey <CAPS> {\t[ 0xffe5 ] };\n";
        assert!(text.contains(caps), "fixture shape");
        let crafted = text.replace(
            caps,
            "\tkey <CAPS> {\n\t\trepeat= No,\n\t\tvmods= NumLock,\n\t\t\
             symbols[1]= [ 0xffe5 ],\n\t\tactions[1]= [ LockMods(modifiers=Mod3) ]\n\t};\n",
        );
        let before = compile(&dump(&compile(&crafted)));
        let input = dump(&before);
        assert!(input.contains("repeat= No") || input.contains("repeat=No"));
        assert!(input.contains("actions[1]"), "explicit action is dumped");

        // Rebind the key to Control_L: the interpret for Control_L would give
        // SetMods(Control), but the explicit LockMods(Mod3) must survive.
        let spec = [KeyGroupSpec {
            type_name: None,
            keysyms: vec![0xffe3],
        }];
        let after = compile(&set_key(&input, "CAPS", &spec).expect("set"));
        let caps_kc = Keycode::new(66);
        assert_eq!(after.key_get_syms_by_level(caps_kc, 0, 0)[0].raw(), 0xffe3);
        assert_eq!(after.key_repeats(caps_kc), before.key_repeats(caps_kc));
        assert!(!after.key_repeats(caps_kc));
        let locked = |k: &Keymap| {
            let mut st = xkb::State::new(k);
            st.update_key(caps_kc, xkb::KeyDirection::Down);
            st.update_key(caps_kc, xkb::KeyDirection::Up);
            st.serialize_mods(xkb::STATE_MODS_LOCKED)
        };
        assert_ne!(locked(&before), 0, "precondition: the action locks");
        assert_eq!(locked(&after), locked(&before), "explicit action kept");
        assert_untouched(&before, &after, &[66]);
    }

