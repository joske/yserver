//! Edits over xkbcommon's V1 keymap dump (#171).
//!
//! xkbcommon keymaps are immutable and expose no structured access to types,
//! actions or behaviors, so a runtime mapping change (ChangeKeyboardMapping,
//! SetModifierMapping) takes the live keymap's
//! `get_as_string(KEYMAP_FORMAT_TEXT_V1)`, edits it here, and hands the result
//! to [`crate::kms::core::KmsCore::install_keymap_text`]. The compiler then
//! re-derives actions and the vmodmap from the compat interprets, which is what
//! Xorg's `XkbUpdateDescActions` does after `XkbUpdateKeyTypesFromCore`.
//!
//! The input is machine-generated by xkbcommon's serializer, and the parser
//! relies on that shape: sections open at the start of a line
//! (`xkb_keycodes "…" {`, `xkb_symbols "…" {`), every statement ends in `;`,
//! strings are double-quoted, and there are no comments. Braces, brackets and
//! strings are still matched properly, so nested `{ … }` (multi-keysym levels)
//! and bracketed lists never confuse a statement boundary.

use std::{collections::HashSet, fmt, ops::Range};

use crate::kms::xkb::REAL_MOD_NAMES;

/// `XkbNumKbdGroups`: a key has at most four groups.
const MAX_GROUPS: usize = 4;

/// `XKB_KEYSYM_MAX`: the largest keysym libxkbcommon accepts.
const KEYSYM_MAX: u32 = 0x1fff_ffff;

/// One group of a key as a runtime mapping change describes it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct KeyGroupSpec {
    /// Explicit key type; `None` lets the compiler pick one from the keysyms.
    pub type_name: Option<String>,
    /// One keysym per shift level, level 1 first; `0` is `NoSymbol`.
    pub keysyms: Vec<u32>,
}

/// Why an edit of the keymap text was refused. The text is left unchanged.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) enum XkbEditError {
    /// The text has no `xkb_keycodes` / `xkb_symbols` section.
    MissingSection(&'static str),
    /// A brace, bracket or string in the named section doesn't close.
    Malformed(&'static str),
    /// The key name is neither a keycode name nor an alias.
    UnknownKey(String),
    /// More groups than XKB allows.
    TooManyGroups(usize),
    /// A type name that can't be written as an XKB string.
    BadTypeName(String),
    /// Keycodes below 8 don't exist in X.
    InvalidKeycode(u8),
    /// Every candidate name for the keycode is already taken.
    NoFreeKeyName(u8),
    /// The keycode is in more than one modifier; keymap text keeps one per
    /// key (xkbcommon and xkbcomp both drop all but the last).
    MultipleModifiers(u8),
}

impl fmt::Display for XkbEditError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::MissingSection(s) => write!(f, "keymap text has no {s} section"),
            Self::Malformed(s) => write!(f, "unbalanced brace, bracket or string in {s}"),
            Self::UnknownKey(k) => write!(f, "no key named <{k}>"),
            Self::TooManyGroups(n) => write!(f, "{n} groups (XKB allows {MAX_GROUPS})"),
            Self::BadTypeName(t) => write!(f, "type name {t:?} can't be written"),
            Self::InvalidKeycode(kc) => write!(f, "keycode {kc} is below the X minimum of 8"),
            Self::NoFreeKeyName(kc) => write!(f, "no free key name for keycode {kc}"),
            Self::MultipleModifiers(kc) => {
                write!(
                    f,
                    "keycode {kc} is in several modifiers; XKB text allows one"
                )
            }
        }
    }
}

impl std::error::Error for XkbEditError {}

/// The name `keycode` has in `xkb_keycodes` (not an alias), if any.
pub(crate) fn keycode_name(text: &str, keycode: u8) -> Result<Option<String>, XkbEditError> {
    let body = section(text, "xkb_keycodes")?;
    Ok(statements(text, body, "xkb_keycodes")?
        .into_iter()
        .filter_map(|r| keycode_def(&text[r]))
        .find(|&(_, kc)| kc == u32::from(keycode))
        .map(|(name, _)| name.to_owned()))
}

/// Make sure `keycode` has a name in `xkb_keycodes`, adding `<Innn> = nnn;`
/// when it has none (ChangeKeyboardMapping and SetModifierMapping may target
/// a keycode the keymap never named). Returns the text and the name.
pub(crate) fn ensure_keycode_name(
    text: &str,
    keycode: u8,
) -> Result<(String, String), XkbEditError> {
    if keycode < 8 {
        return Err(XkbEditError::InvalidKeycode(keycode));
    }
    let body = section(text, "xkb_keycodes")?;
    let stmts = statements(text, body.clone(), "xkb_keycodes")?;
    let mut taken = HashSet::new();
    let mut last_def: Option<Range<usize>> = None;
    let mut minimum: Option<(Range<usize>, u32)> = None;
    let mut maximum: Option<(Range<usize>, u32)> = None;
    for r in &stmts {
        let stmt = &text[r.clone()];
        if let Some((name, kc)) = keycode_def(stmt) {
            if kc == u32::from(keycode) {
                return Ok((text.to_owned(), name.to_owned()));
            }
            taken.insert(name.to_owned());
            last_def = Some(r.clone());
        } else if let Some(alias) = alias_def(stmt) {
            taken.insert(alias.to_owned());
        } else if let Some(v) = assignment(stmt, "minimum") {
            minimum = Some((r.clone(), v));
        } else if let Some(v) = assignment(stmt, "maximum") {
            maximum = Some((r.clone(), v));
        }
    }
    // Four characters at most: key names are 4 bytes on the X wire.
    let name = ['I', 'J', 'K', 'L']
        .iter()
        .map(|p| format!("{p}{keycode:03}"))
        .find(|n| !taken.contains(n))
        .ok_or(XkbEditError::NoFreeKeyName(keycode))?;

    let kc = u32::from(keycode);
    let mut edits: Vec<(Range<usize>, String)> = Vec::new();
    if let Some((r, v)) = minimum
        && kc < v
    {
        edits.push((r, format!("minimum = {kc};")));
    }
    if let Some((r, v)) = maximum
        && kc > v
    {
        edits.push((r, format!("maximum = {kc};")));
    }
    let line = format!("\t<{name}> = {kc};\n");
    let at = last_def.map_or(body.start, |r| line_extent(text, r).end);
    if at == body.start && !text[..at].ends_with('\n') {
        edits.push((at..at, format!("\n{line}")));
    } else {
        edits.push((at..at, line));
    }
    Ok((apply_edits(text, edits), name))
}

/// Replace the `key <name> { … };` entry of `xkb_symbols` with one carrying
/// `groups` (inserting it when the key has no entry yet). The key's other
/// explicit properties (`repeat=`, `vmods=`, and `actions[]` of groups that
/// still exist) are kept: Xorg leaves a key's explicit actions alone on a
/// mapping change (`XkbUpdateDescActions` skips `XkbExplicitInterpretMask`
/// keys), and the compiler derives everything else from the new keysyms.
/// No groups removes the symbols; the entry goes away if nothing else is left.
pub(crate) fn set_key(
    text: &str,
    name: &str,
    groups: &[KeyGroupSpec],
) -> Result<String, XkbEditError> {
    if groups.len() > MAX_GROUPS {
        return Err(XkbEditError::TooManyGroups(groups.len()));
    }
    for ty in groups.iter().filter_map(|g| g.type_name.as_deref()) {
        if ty.is_empty() || ty.chars().any(|c| c == '"' || c == '\\' || c.is_control()) {
            return Err(XkbEditError::BadTypeName(ty.to_owned()));
        }
    }
    let canonical = canonical_key_name(text, name)?;
    let body = section(text, "xkb_symbols")?;
    let stmts = statements(text, body.clone(), "xkb_symbols")?;
    let existing = stmts
        .iter()
        .find(|r| key_stmt_name(&text[(*r).clone()]) == Some(canonical.as_str()))
        .cloned();

    let (kept, actions) = match &existing {
        Some(r) => kept_key_fields(&text[r.clone()], groups.len())?,
        None => (Vec::new(), Vec::new()),
    };
    let entry = render_key(&canonical, &kept, groups, &actions);

    let edit = match existing {
        Some(r) => (line_extent(text, r), entry),
        None => {
            let at = stmts
                .iter()
                .find(|r| is_modifier_map(&text[(*r).clone()]))
                .map_or(body.end, |r| line_extent(text, r.clone()).start);
            if !entry.is_empty() && !text[..at].ends_with('\n') {
                (at..at, format!("\n{entry}"))
            } else {
                (at..at, entry)
            }
        }
    };
    Ok(apply_edits(text, vec![edit]))
}

/// Rewrite every `modifier_map` statement of `xkb_symbols` from a per-keycode
/// real-modifier mask (Xorg's `xkb->map->modmap`; bit 0 Shift … bit 7 Mod5).
/// Keycodes with bits set and no name get one ([`ensure_keycode_name`]).
/// A keycode in several modifiers is refused: the compiler keeps only one
/// modifier per key, so writing it would silently lose the others.
pub(crate) fn set_modifier_map(text: &str, modmap: &[u8; 256]) -> Result<String, XkbEditError> {
    if let Some(kc) = (0..=255u8).find(|&kc| modmap[usize::from(kc)].count_ones() > 1) {
        return Err(XkbEditError::MultipleModifiers(kc));
    }
    let mut text = text.to_owned();
    let mut names: Vec<(u8, String)> = Vec::new();
    for kc in 0..=255u8 {
        if modmap[usize::from(kc)] == 0 {
            continue;
        }
        let (named, name) = ensure_keycode_name(&text, kc)?;
        text = named;
        names.push((kc, name));
    }

    let body = section(&text, "xkb_symbols")?;
    let stmts = statements(&text, body.clone(), "xkb_symbols")?;
    let mut edits: Vec<(Range<usize>, String)> = stmts
        .iter()
        .filter(|r| is_modifier_map(&text[(*r).clone()]))
        .map(|r| (line_extent(&text, r.clone()), String::new()))
        .collect();

    let mut block = String::new();
    for (bit, mod_name) in REAL_MOD_NAMES.iter().enumerate() {
        let keys: Vec<String> = names
            .iter()
            .filter(|(kc, _)| modmap[usize::from(*kc)] & (1 << bit) != 0)
            .map(|(_, n)| format!("<{n}>"))
            .collect();
        if !keys.is_empty() {
            block.push_str(&format!(
                "\tmodifier_map {mod_name} {{ {} }};\n",
                keys.join(", ")
            ));
        }
    }
    if !block.is_empty() {
        let at = body.end;
        if !text[..at].ends_with('\n') {
            block.insert(0, '\n');
        }
        edits.push((at..at, block));
    }
    Ok(apply_edits(&text, edits))
}

