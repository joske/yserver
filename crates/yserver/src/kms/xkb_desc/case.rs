/// `UCSConvertCase`: simple one-to-one case mappings of a UCS code point.
fn ucs_convert_case(code: u32) -> (u32, u32) {
    let (mut lower, mut upper) = (code, code);
    let table = |t: &[u16], base: u32| u32::from(t[(code - base) as usize]);
    if code <= 0x00ff {
        if (0x0041..=0x005a).contains(&code) {
            lower += 0x20;
        } else if (0x0061..=0x007a).contains(&code) {
            upper -= 0x20;
        } else if (0x00c0..=0x00d6).contains(&code) || (0x00d8..=0x00de).contains(&code) {
            lower += 0x20;
        } else if (0x00e0..=0x00f6).contains(&code) || (0x00f8..=0x00fe).contains(&code) {
            upper -= 0x20;
        } else if code == 0x00ff {
            upper = 0x0178;
        } else if code == 0x00b5 {
            upper = 0x039c;
        } else if code == 0x00df {
            upper = 0x1e9e;
        }
        return (lower, upper);
    }
    if code <= 0x017f {
        if (0x0100..=0x012f).contains(&code)
            || (0x0132..=0x0137).contains(&code)
            || (0x014a..=0x0177).contains(&code)
        {
            upper = code & !1;
            lower = code | 1;
        } else if (0x0139..=0x0148).contains(&code) || (0x0179..=0x017e).contains(&code) {
            if code & 1 != 0 {
                lower += 1;
            } else {
                upper -= 1;
            }
        } else if code == 0x0130 {
            lower = 0x0069;
        } else if code == 0x0131 {
            upper = 0x0049;
        } else if code == 0x0178 {
            lower = 0x00ff;
        } else if code == 0x017f {
            upper = 0x0053;
        }
        return (lower, upper);
    }
    if code <= 0x024f {
        if (0x0180..=0x01cc).contains(&code) {
            lower = table(&LATINEXTB_LOWER_MAPPING, 0x0180);
            upper = table(&LATINEXTB_UPPER_MAPPING, 0x0180);
        } else if (0x01cd..=0x01dc).contains(&code) {
            if code & 1 != 0 {
                lower += 1;
            } else {
                upper -= 1;
            }
        } else if code == 0x01dd {
            upper = 0x018e;
        } else if (0x01de..=0x01ef).contains(&code)
            || (0x01f4..=0x01f5).contains(&code)
            || (0x01f8..=0x021f).contains(&code)
            || (0x0222..=0x0233).contains(&code)
        {
            lower |= 1;
            upper &= !1;
        } else if code == 0x01f1 || code == 0x01f2 {
            lower = 0x01f3;
            upper = 0x01f1;
        } else if code == 0x01f3 {
            upper = 0x01f1;
        } else if code == 0x01f6 {
            lower = 0x0195;
        } else if code == 0x01f7 {
            lower = 0x01bf;
        } else if code == 0x0220 {
            lower = 0x019e;
        }
        return (lower, upper);
    }
    if (0x0253..=0x0292).contains(&code) {
        return (lower, table(&IPAEXT_UPPER_MAPPING, 0x0253));
    }
    if code == 0x0345 {
        return (lower, 0x0399);
    }
    if (0x0370..=0x03ff).contains(&code) {
        lower = table(&GREEK_LOWER_MAPPING, 0x0370);
        upper = table(&GREEK_UPPER_MAPPING, 0x0370);
        if upper == 0 {
            upper = code;
        }
        if lower == 0 {
            lower = code;
        }
        return (lower, upper);
    }
    if (0x0400..=0x052f).contains(&code) {
        if (0x0400..=0x040f).contains(&code) {
            lower += 0x50;
        } else if (0x0410..=0x042f).contains(&code) {
            lower += 0x20;
        } else if (0x0430..=0x044f).contains(&code) {
            upper -= 0x20;
        } else if (0x0450..=0x045f).contains(&code) {
            upper -= 0x50;
        } else if (0x0460..=0x0481).contains(&code)
            || (0x048a..=0x04bf).contains(&code)
            || (0x04d0..=0x04f5).contains(&code)
            || (0x04f8..=0x04f9).contains(&code)
            || (0x0500..=0x050f).contains(&code)
        {
            upper &= !1;
            lower |= 1;
        } else if (0x04c1..=0x04ce).contains(&code) {
            if code & 1 != 0 {
                lower += 1;
            } else {
                upper -= 1;
            }
        }
        return (lower, upper);
    }
    if (0x0530..=0x058f).contains(&code) {
        if (0x0531..=0x0556).contains(&code) {
            lower += 0x30;
        } else if (0x0561..=0x0586).contains(&code) {
            upper -= 0x30;
        }
        return (lower, upper);
    }
    if (0x1e00..=0x1eff).contains(&code) {
        if (0x1e00..=0x1e95).contains(&code) || (0x1ea0..=0x1ef9).contains(&code) {
            upper &= !1;
            lower |= 1;
        } else if code == 0x1e9b {
            upper = 0x1e60;
        } else if code == 0x1e9e {
            lower = 0x00df;
        }
        return (lower, upper);
    }
    if (0x1f00..=0x1fff).contains(&code) {
        lower = table(&GREEKEXT_LOWER_MAPPING, 0x1f00);
        upper = table(&GREEKEXT_UPPER_MAPPING, 0x1f00);
        if upper == 0 {
            upper = code;
        }
        if lower == 0 {
            lower = code;
        }
        return (lower, upper);
    }
    if (0x2100..=0x214f).contains(&code) {
        match code {
            0x2126 => lower = 0x03c9,
            0x212a => lower = 0x006b,
            0x212b => lower = 0x00e5,
            _ => {}
        }
    } else if (0x2160..=0x216f).contains(&code) {
        lower += 0x10;
    } else if (0x2170..=0x217f).contains(&code) {
        upper -= 0x10;
    } else if (0x24b6..=0x24cf).contains(&code) {
        lower += 0x1a;
    } else if (0x24d0..=0x24e9).contains(&code) {
        upper -= 0x1a;
    } else if (0xff21..=0xff3a).contains(&code) {
        lower += 0x20;
    } else if (0xff41..=0xff5a).contains(&code) {
        upper -= 0x20;
    } else if (0x10400..=0x10427).contains(&code) {
        lower += 0x28;
    } else if (0x10428..=0x1044f).contains(&code) {
        upper -= 0x28;
    }
    (lower, upper)
}

/// libX11's `XConvertCase`: `(lower, upper)`.
pub(crate) fn xconvert_case(sym: u32) -> (u32, u32) {
    if sym < 0x100 {
        return match sym {
            0x00ff => (sym, 0x13be),      // ydiaeresis → Ydiaeresis
            0x00b5 => (sym, 0x07cc),      // mu → Greek_MU
            0x00df => (sym, 0x0100_1e9e), // ssharp → U+1E9E
            _ => ucs_convert_case(sym),
        };
    }
    if sym & 0xff00_0000 == 0x0100_0000 {
        let (mut lower, mut upper) = ucs_convert_case(sym & 0x00ff_ffff);
        if upper >= 0x100 {
            upper |= 0x0100_0000;
        }
        if lower >= 0x100 {
            lower |= 0x0100_0000;
        }
        return (lower, upper);
    }
    let (mut lower, mut upper) = (sym, sym);
    match sym >> 8 {
        1 => {
            if sym == 0x1a1 {
                lower = 0x1b1;
            } else if (0x1a3..=0x1a6).contains(&sym)
                || (0x1a9..=0x1ac).contains(&sym)
                || (0x1ae..=0x1af).contains(&sym)
            {
                lower += 0x10;
            } else if sym == 0x1b1 {
                upper = 0x1a1;
            } else if (0x1b3..=0x1b6).contains(&sym)
                || (0x1b9..=0x1bc).contains(&sym)
                || (0x1be..=0x1bf).contains(&sym)
            {
                upper -= 0x10;
            } else if (0x1c0..=0x1de).contains(&sym) {
                lower += 0x20;
            } else if (0x1e0..=0x1fe).contains(&sym) {
                upper -= 0x20;
            }
        }
        2 => {
            if (0x2a1..=0x2a6).contains(&sym) || (0x2ab..=0x2ac).contains(&sym) {
                lower += 0x10;
            } else if (0x2b1..=0x2b6).contains(&sym) || (0x2bb..=0x2bc).contains(&sym) {
                upper -= 0x10;
            } else if (0x2c5..=0x2de).contains(&sym) {
                lower += 0x20;
            } else if (0x2e5..=0x2fe).contains(&sym) {
                upper -= 0x20;
            }
        }
        3 => {
            if (0x3a3..=0x3ac).contains(&sym) {
                lower += 0x10;
            } else if (0x3b3..=0x3bc).contains(&sym) {
                upper -= 0x10;
            } else if sym == 0x3bd {
                lower = 0x3bf;
            } else if sym == 0x3bf {
                upper = 0x3bd;
            } else if (0x3c0..=0x3de).contains(&sym) {
                lower += 0x20;
            } else if (0x3e0..=0x3fe).contains(&sym) {
                upper -= 0x20;
            }
        }
        6 => {
            if (0x6b1..=0x6bf).contains(&sym) {
                lower -= 0x10;
            } else if (0x6a1..=0x6af).contains(&sym) {
                upper += 0x10;
            } else if (0x6e0..=0x6ff).contains(&sym) {
                lower -= 0x20;
            } else if (0x6c0..=0x6df).contains(&sym) {
                upper += 0x20;
            }
        }
        7 => {
            if (0x7a1..=0x7ab).contains(&sym) {
                lower += 0x10;
            } else if (0x7b1..=0x7bb).contains(&sym) && sym != 0x7b6 && sym != 0x7ba {
                upper -= 0x10;
            } else if (0x7c1..=0x7d9).contains(&sym) {
                lower += 0x20;
            } else if sym == 0x7f3 {
                upper = 0x7d2;
            } else if (0x7e1..=0x7f9).contains(&sym) {
                upper -= 0x20;
            }
        }
        0x13 => {
            if sym == 0x13bc {
                lower = 0x13bd;
            } else if sym == 0x13bd {
                upper = 0x13bc;
            } else if sym == 0x13be {
                lower = 0xff;
            }
        }
        _ => {}
    }
    (lower, upper)
}

